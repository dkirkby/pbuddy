@pytest.fixture(scope="session")
def synthetic_video(tmp_path_factory) -> Path:
    """Generate a 12-second 640x360 synthetic video using ffmpeg."""
    out = tmp_path_factory.mktemp("video") / "synthetic.mp4"
    # Two 5-second segments: first with colour bars (simulates motion), then a
    # static grey scene (simulates stable play), then colour bars again.
    cmd = [
        "ffmpeg", "-y",
        "-f", "lavfi",
        "-i", "color=c=gray:s=640x360:r=30:d=12",
        "-c:v", "libx264", "-preset", "ultrafast", "-t", "12",
        str(out),
    ]
    result = subprocess.run(cmd, capture_output=True)
    assert result.returncode == 0, f"ffmpeg failed: {result.stderr.decode()}"
    return out


