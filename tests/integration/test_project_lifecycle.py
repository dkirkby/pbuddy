@pytest.mark.asyncio
async def test_queue_pass1(client, synthetic_video):
    # Create project + upload.
    resp = await client.post("/api/projects", json={"name": "Pass1 Test"})
    project_id = resp.json()["id"]
    with open(synthetic_video, "rb") as f:
        await client.post(
            f"/api/projects/{project_id}/video",
            files={"file": ("synthetic.mp4", f, "video/mp4")},
        )

    # Queue pass 1.
    resp = await client.post(f"/api/projects/{project_id}/passes/pass1/run")
    assert resp.status_code == 200
    job = resp.json()["data"]
    assert job["status"] == "queued"
    assert job["pass_name"] == "pass1"

    # Pass state should be queued.
    resp = await client.get(f"/api/projects/{project_id}/passes/pass1")
    assert resp.json()["data"]["state"] == "queued"


@pytest.mark.asyncio
async def test_pass1_full_lifecycle(client, synthetic_video, app_with_tmp_data):
    """Run Pass 1 via the worker directly, then submit corrections and accept."""
    app, data_root = app_with_tmp_data

    # Create + upload.
    resp = await client.post("/api/projects", json={"name": "Lifecycle Test"})
    project_id = resp.json()["id"]
    with open(synthetic_video, "rb") as f:
        await client.post(
            f"/api/projects/{project_id}/video",
            files={"file": ("synthetic.mp4", f, "video/mp4")},
        )

    # Queue pass 1 via API.
    resp = await client.post(f"/api/projects/{project_id}/passes/pass1/run")
    assert resp.status_code == 200
    job_id = resp.json()["data"]["id"]

    # Run the worker synchronously (bypassing the subprocess) to avoid waiting.
    from pbva_core.config import Settings
    settings = Settings()
    from pbva_db.engine import get_engine, get_session_factory, init_db
    engine = get_engine(settings.db_path)
    session_factory = get_session_factory(engine)

    from pbva_worker.worker_loop import execute_job
    with session_factory() as session:
        from pbva_db.models import Job
        job = session.get(Job, job_id)

    execute_job(job, settings, session_factory)

    # Pass should now be waiting_for_user.
    resp = await client.get(f"/api/projects/{project_id}/passes/pass1")
    assert resp.json()["data"]["state"] == "waiting_for_user"

    # Artifacts should be registered.
    resp = await client.get(f"/api/projects/{project_id}/passes/pass1/artifacts")
    arts = resp.json()["data"]
    assert any(a["artifact_type"] == "png" for a in arts)

    # Submit corrections (empty — no changes).
    resp = await client.put(f"/api/projects/{project_id}/passes/pass1/corrections", json={})
    assert resp.status_code == 200

    # Accept pass 1.
    resp = await client.post(f"/api/projects/{project_id}/passes/pass1/accept")
    assert resp.status_code == 200

    # Project status should be in_progress.
    resp = await client.get(f"/api/projects/{project_id}")
    data = resp.json()
    assert data["status"] == "in_progress"

    # Pass state should be accepted.
    pass1 = next(p for p in data["passes"] if p["pass_name"] == "pass1")
    assert pass1["state"] == "accepted"

    # Accepted result.json must exist on disk.
    from pbva_core import paths as p_paths
    accepted_path = p_paths.pass_accepted_dir(settings.data_root, project_id, "pass1") / "result.json"
    assert accepted_path.exists(), "accepted/result.json not written"

    # Reload project (simulate browser reload).
    resp = await client.get(f"/api/projects/{project_id}")
    assert resp.json()["status"] == "in_progress"
